TEXTS = {k: (g, label, default) for g, k, label, default in _ITEMS}
GROUPS = list(dict.fromkeys(g for g, *_ in _ITEMS))


def default(key):
    return TEXTS[key][2]


def raw(key):
    r = db.one("SELECT value FROM settings WHERE key=?", (key,))
    return r["value"] if r else default(key)


def t(key, **kw):
    s = raw(key)
    for k, v in kw.items():
        s = s.replace("{" + k + "}", str(v))
    return s


def placeholders(key):
    return sorted(set(re.findall(r"\{(\w+)\}", default(key))))


def is_custom(key):
    r = db.one("SELECT value FROM settings WHERE key=?", (key,))
    return bool(r) and r["value"] != default(key)


def reset(key):
    db.ex("DELETE FROM settings WHERE key=?", (key,))
